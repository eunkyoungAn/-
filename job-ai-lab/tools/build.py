def md_to_docx(md_path, docx_path):
    from docx import Document
    from docx.shared import Pt
    from docx.oxml.ns import qn
    doc = Document()
    st = doc.styles['Normal']
    st.font.name = 'Malgun Gothic'
    st.element.rPr.rFonts.set(qn('w:eastAsia'), 'Malgun Gothic')
    st.font.size = Pt(10.5)
    for s in ('Heading 1', 'Heading 2', 'Heading 3'):
        doc.styles[s].font.name = 'Malgun Gothic'
        doc.styles[s].element.rPr.rFonts.set(qn('w:eastAsia'), 'Malgun Gothic')

    def add_runs(par, text):
        for i, part in enumerate(re.split(r'\*\*', text)):
            if part:
                par.add_run(part).bold = (i % 2 == 1)

    lines = open(md_path, encoding='utf-8').read().splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i]
        if ln.startswith('|'):
            rows = []
            while i < len(lines) and lines[i].startswith('|'):
                cells = [c.strip() for c in lines[i].strip().strip('|').split('|')]
                if not all(re.fullmatch(r':?-+:?', c) for c in cells):
                    rows.append(cells)
                i += 1
            t = doc.add_table(rows=len(rows), cols=len(rows[0]))
            t.style = 'Table Grid'
            for r, cells in enumerate(rows):
                for c, val in enumerate(cells):
                    cell = t.cell(r, c)
                    cell.text = ''
                    add_runs(cell.paragraphs[0], val)
                    if r == 0:
                        for run in cell.paragraphs[0].runs:
                            run.bold = True
            doc.add_paragraph()
            continue
        m = re.match(r'(#{1,3}) (.*)', ln)
        if m:
            doc.add_heading(m.group(2), level=len(m.group(1)))
        elif ln.startswith('> '):
            p = doc.add_paragraph()
            r = p.add_run(ln[2:])
            r.italic = True
        elif re.match(r'\d+\. ', ln):
            add_runs(doc.add_paragraph(style='List Number'), re.sub(r'^\d+\. ', '', ln))
        elif ln.startswith('- '):
            add_runs(doc.add_paragraph(style='List Bullet'), ln[2:])
        elif ln.strip():
            add_runs(doc.add_paragraph(), ln)
        i += 1
    doc.save(docx_path)


def docx_to_pdf(docx_path, outdir):
    subprocess.run(['soffice', '--headless', '--convert-to', 'pdf', '--outdir', outdir, docx_path],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def build_files():
    os.makedirs(OUT, exist_ok=True)
    for name in sorted(os.listdir(OUT)):
        p = os.path.join(OUT, name)
        shutil.rmtree(p) if os.path.isdir(p) else os.remove(p)
    for grp in FILES:
        for base, _ in grp['items']:
            dx = os.path.join(OUT, base + '.docx')
            md_to_docx(os.path.join(SRC, base + '.md'), dx)
            docx_to_pdf(dx, OUT)
    shutil.copyfile(os.path.join(ROOT, 'sheet', 'FormSetup.gs'), os.path.join(OUT, SCRIPT_FILE))
    build_zip()


def build_zip():
    """files/ 에 있는 파일로 전체 압축 파일을 다시 묶는다."""
    with zipfile.ZipFile(os.path.join(OUT, ZIP_NAME), 'w', zipfile.ZIP_DEFLATED) as z:
        for grp in FILES:
            for base, _ in grp['items']:
                for ext in ('pdf', 'docx'):
                    z.write(os.path.join(OUT, f'{base}.{ext}'), f'{grp["group"]}/{base}.{ext}')
        z.write(os.path.join(OUT, SCRIPT_FILE), f'실습 도구/{SCRIPT_FILE}')



import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = os.path.join(ROOT, 'files')


def read(rel):
    with open(os.path.join(FILES, rel), encoding='utf-8') as f:
        return f.read()


def prompt_of(rel):
    """프롬프트.md 에서 '[공통 작성 규칙'으로 시작하는 지시문 상자를 꺼낸다."""
    text = read(rel)
    for m in re.finditer(r'^(```+|~~~+)text\n(.*?)\n\1\s*$', text, re.S | re.M):
        if m.group(2).lstrip().startswith('[공통 작성 규칙'):
            return m.group(2).strip()
    sys.exit('지시문 상자를 찾지 못함: ' + rel)


def code_block(rel):
    m = re.search(r'^```\n(.*?)\n```', read(rel), re.S | re.M)
    return m.group(1).strip()


def inquiries():
    import openpyxl
    wb = openpyxl.load_workbook(os.path.join(FILES, '실습5_참여자문의응대/가상데이터_참여자문의.xlsx'), read_only=True)
    rows = list(wb['문의기록'].iter_rows(values_only=True))[1:]
    return [{'id': r[0], 'type': r[3], 'q': r[4]} for r in rows if r and r[0]]


def cal_block():
    m = re.search(r'(\[캘린더 일정\].*?\[캘린더 일정 끝\])', read('실습7_일정관리/가상일정_붙여넣기용.md'), re.S)
    return m.group(1)


def F(path, label, role):
    assert os.path.exists(os.path.join(FILES, path)), path
    return {'path': path, 'name': os.path.basename(path), 'label': label, 'role': role}


def V(label, value, kind='text', note=''):
    """kind: text(복사해 붙여넣기) · pick(단추에서 고르기) · file(파일 올리기)"""
    return {'label': label, 'value': value, 'kind': kind, 'note': note}


def S(title, rel):
    return {'title': title, 'file': os.path.basename(rel), 'path': rel, 'text': read(rel)}


